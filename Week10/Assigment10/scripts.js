// Step 2: Check that the script is properly linked
console.log("DOM HW loaded");

/* ============================================
   SELECTORS (all grouped at the top)
   ============================================ */
// Title and main section
const titleEl = document.getElementById("petTitle");
const mainEl = document.getElementById("petMain");
// Intro paragraph (selected by class with querySelector)
const introEl = document.querySelector(".petIntro");
// Image, caption and list
const imgEl = document.getElementById("petImg");
const captionEl = document.getElementById("petCaption");
const listEl = document.getElementById("petList");
// Buttons
const toggleBtn = document.getElementById("petToggleBtn");
const swapBtn = document.getElementById("petSwapBtn");
const darkBtn = document.getElementById("petDarkBtn");
// Part 9 paragraph
const challengeEl = document.getElementById("petChallenge");

// I Separate this part to keep things more organized.

/* ============================================
   DATA: my 4 pets
   ============================================ */
const pets = [
  { name: "Canela", info: "Little white bunny with tan-colored spots", img: "images/canela.jpg" },
  { name: "Panchita", info: "Black rabbit that loves sleeping on its blanket", img: "images/Panchita.jpg" },
  { name: "Pelusa", info: "Black Schnauzer dog with curly fur and a tender gaze", img: "images/Pelusa.jpg" },
  { name: "Gringo", info: "Old, white, very furry rabbit", img: "images/Gringo.jpg" }
];

/* ============================================
   Step 3: Select and update text content
   ============================================ */
// Change the title text
titleEl.textContent = "My dear pets — Powered by JavaScript";
// Change the intro text (using the selected class element)
introEl.textContent = "Meet my 4 pets; this list and these photos are generated by JavaScript..";

/* ============================================
   Step 4: Change attributes (image)
   ============================================ */
// Set the first image and its alt text from the data array
imgEl.src = pets[0].img;
imgEl.alt = `Pic of ${pets[0].name}, ${pets[0].info}`;
captionEl.textContent = `Showing: ${pets[0].name}`; // I use this, mentioning the pet's name; I use this part of the AI ​​to know exactly which command to use.

/* ============================================
   Step 5: Render the data array into the DOM
   ============================================ */
// Clear any existing items

listEl.innerHTML = "";

// Create an <li> for each pet and append it to the list

pets.forEach((pet) => {
  const li = document.createElement("li");
  li.textContent = `${pet.name} — ${pet.info}`;
  listEl.appendChild(li);
});

/* ============================================
   Step 6: Toggle a class to change styles
   ============================================ */
// Toggle the highlight class on <main>

toggleBtn.addEventListener("click", () => {
  mainEl.classList.toggle("petHighlight");
});

// (Optional) Toggle dark mode on <body>
darkBtn.addEventListener("click", () => {
  document.body.classList.toggle("petDark");
});

/* ============================================
   Step 7: Wire an action that updates attributes on click (Swap the image )
   ============================================ */
// Keeps track of which pet is currently shown
const petswapBtn = document.getElementById("petSwapBtn");
let swapped = 0;

petswapBtn.addEventListener("click", () => {
    if (swapped === 0) {
        imgEl.src = "images/Panchita.jpg";
        imgEl.alt = "Panchita";
        captionEl.textContent = "This is: Panchita";
        swapped = 1;

    } else if (swapped === 1) {
        imgEl.src = "images/Pelusa.jpg";
        imgEl.alt = "Pelusa";
        captionEl.textContent = "This is: Pelusa";
        swapped = 2;

    } else if (swapped === 2) {
        imgEl.src = "images/Gringo.jpg";
        imgEl.alt = "Gringo";
        captionEl.textContent = "This is: Gringo";
        swapped = 3;

    } else if (swapped === 3) {
        imgEl.src = "images/canela.jpg";
        imgEl.alt = "Canela";
        captionEl.textContent = "This is: Canela";
        swapped = 0;
    }
}); // In this part, I looked for another way to change the image, 
// since the command available in Canva wasn't working correctly.
/* ============================================
   Part 9: Independent DOM Challenge
   ============================================ */
// Change the text and color of the new paragraph
challengeEl.textContent = "This text was modified by JavaScript.";
